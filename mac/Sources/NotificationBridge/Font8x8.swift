/// 8x8 bitmap font for the cracktro, ascii 32 (space) to 90 (Z); each glyph is 8 rows, top row in the high byte,
/// leftmost pixel in each row's high bit
enum Font8x8 {
    static func glyph(_ character: Character) -> UInt64 {
        guard let code = character.uppercased().unicodeScalars.first?.value, code >= 32, code < 32 + UInt32(glyphs.count)
        else { return 0 }
        return glyphs[Int(code) - 32]
    }

    static func pixel(_ glyph: UInt64, x: Int, y: Int) -> Bool {
        glyph >> UInt64(63 - y * 8 - x) & 1 != 0
    }

